#!/usr/bin/env python3
"""Generate the Android model assets from the frozen inventory, without evaluating JSX."""
import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    subprocess.run(["python3", str(ROOT / "tools/verify_rapidraw_reference.py")], check=True)
    reference = ROOT / "third_party/rapidraw-reference"
    catalog = json.loads((ROOT / "docs/rapidraw-inventory/catalog.json").read_text())
    default_bytes = (reference / "src/utils/defaultAdjustments.json").read_bytes()
    defaults = json.loads(default_bytes)
    ranges = {}
    for control in catalog["controls"]:
        if "/adjustments/" not in control["source"]["path"]:
            continue
        props = control["properties"]
        match = re.fullmatch(r"adjustments\.([\wé]+)(?:\s*\?\?\s*[\d.]+)?", props.get("value", ""))
        if not match or match[1] not in defaults:
            continue
        key = match[1]
        try:
            low, high, step = float(props["min"]), float(props["max"]), float(props.get("step", "1"))
        except (KeyError, ValueError):
            continue
        if isinstance(defaults[key], (int, float)) and low <= defaults[key] <= high:
            ranges[key] = dict(min=low, max=high, step=step, source=control["source"])
    schema = dict(engine="rapidraw", version=1, sourceCommit=catalog["commit"], sections=catalog["sections"], ranges=ranges)
    files = {
        ROOT / "app/src/main/assets/rapidraw/defaults.json": default_bytes,
        ROOT / "app/src/main/assets/rapidraw/schema.json": (json.dumps(schema, ensure_ascii=False, indent=2) + "\n").encode(),
        ROOT / "app/src/main/assets/licenses/rapidraw-AGPL-3.0.txt": (reference / "LICENSE").read_bytes(),
    }
    compact_defaults = json.dumps(defaults, ensure_ascii=False, separators=(",", ":"))
    compact_schema = json.dumps(schema, ensure_ascii=False, separators=(",", ":"))
    kotlin = ('// Generated by tools/generate_rapidraw_schema.py; do not edit.\n'
        '// SPDX-License-Identifier: AGPL-3.0-or-later\n'
        'package com.matthew.crs.rapidraw\n\nobject RapidDefaults {\n'
        '    val schema: RapidSchema by lazy { RapidSchema(\n'
        '        """' + compact_defaults + '""",\n'
        '        """' + compact_schema + '""") }\n}\n')
    files[ROOT / "app/src/main/java/com/matthew/crs/rapidraw/RapidDefaults.kt"] = kotlin.encode()
    for path, data in files.items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f"Generated asset differs: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f"{'Verified' if args.check else 'Generated'} {len(defaults)} defaults and {len(ranges)} static numeric bounds; dynamic bounds remain in reference")


if __name__ == "__main__":
    main()
