# Requires Python 3.9+ with opencolorio==2.5.0 and numpy.
# Run from the repository root. Generated shader contains analytical code and
# the reference hue tables, not a baked 3D LUT or a fitted approximation.
import PyOpenColorIO as ocio
import numpy as np
from pathlib import Path
assert ocio.__version__ == '2.5.0'
c=ocio.Config.CreateFromBuiltinConfig('cg-config-v4.0.0_aces-v2.0_ocio-v2.5')
# Include the explicit scene-linear Rec.709 D65 -> AP0 D60 chromatic adaptation.
p=c.getProcessor('Linear Rec.709 (sRGB)','sRGB - Display','ACES 2.0 - SDR 100 nits (Rec.709)',ocio.TRANSFORM_DIR_FORWARD)
d=ocio.GpuShaderDesc.CreateShaderDesc();d.setLanguage(ocio.GPU_LANGUAGE_GLSL_4_0);d.setFunctionName('aces2Output');p.getDefaultGPUProcessor().extractGpuShaderInfo(d)
s=d.getShaderText()
for t in d.getTextures():
    assert t.height==1 and t.width==362 and t.interpolation==ocio.INTERP_NEAREST
    v=np.array(t.getValues()); channels=1 if t.channel==ocio.GpuShaderDesc.TEXTURE_RED_CHANNEL else 3
    vals=v.reshape(-1,channels)
    f=lambda x: format(float(x),'.9g')+('.0' if float(x).is_integer() else '')
    entries=','.join('vec4('+','.join([f(x) for x in a]+['0.0']*(4-channels))+')' for a in vals)
    name=t.samplerName
    s=s.replace('uniform sampler1D '+name+';',f'const vec4 {name}_data[362] = vec4[362]({entries});\nvec4 {name}_fetch(float u) {{ return {name}_data[clamp(int(floor(u*362.0)),0,361)]; }}')
    s=s.replace('texture('+name+', ',name+'_fetch(')
header='// Generated by tools/color/generate_aces.py with OpenColorIO 2.5.0. BSD-3-Clause.\n// Full ACES 2.0 SDR 100-nit Rec.709 / sRGB output transform; no fitted RRT/ODT.\n'
Path('app/src/main/shaders/aces2_output.glsl').write_text(header+s)
# CPU input conversion, including Bradford D65->D60, from the same OCIO config.
mat=c.getProcessor('Linear Rec.709 (sRGB)','ACES2065-1').createGroupTransform()
print(mat)
Path('tests/color/aces2-reference.ctf').write_text(p.createGroupTransform().write('Color Transform Format'))
# Reference vectors also cover negative/wide gamut and extreme highlights.
x=np.concatenate([np.array([[0,0,0],[.18,.18,.18],[1,1,1],[16,16,16],[-.1,.5,2],[4,.2,.01]],np.float32), np.random.default_rng(4).uniform(-.1,16,(200,3)).astype(np.float32)])
y=x.copy();p.getDefaultCPUProcessor().applyRGB(y)
np.savetxt('tests/color/aces2-reference.txt',np.concatenate([x,y],axis=1),fmt='%.9g')
